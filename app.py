@app.route("/callback", methods=['POST'])
def callback():
    signature = request.headers['X-Line-Signature']
    body = request.get_data(as_text=True)
    try:
        handler.handle(body, signature)
    except InvalidSignatureError:
        abort(400)
    return 'OK'

@handler.add(MessageEvent, message=TextMessage)
def handle_message(event):
    text = event.message.text.strip()
    user_id = event.source.user_id

    # 1. กรณีผู้เล่นพิมพ์ "ขอโจทย์"
    if text == "ขอโจทย์":
        puzzle = random.choice(PUZZLES)
        user_puzzles[user_id] = puzzle
        nums_str = " ".join(map(str, puzzle))
        reply = (f"โจทย์มาแล้วจ้า! 🎉\nเลขของคุณคือ: {nums_str}\n\n"
                 f"พิมพ์สมการที่ได้ 24 ตอบกลับมาได้เลยค่ะ (เช่น (8+4)*(4-2))\n"
                 f"พิมพ์ 'ยอมแพ้' เพื่อเปลี่ยนข้อใหม่")
        line_bot_api.reply_message(event.reply_token, TextSendMessage(text=reply))
        return

    # 2. กรณีผู้เล่นขอยอมแพ้เพื่อเปลี่ยนข้อ
    if text == "ยอมแพ้":
        if user_id in user_puzzles:
            del user_puzzles[user_id]
        line_bot_api.reply_message(event.reply_token, TextSendMessage(text="ไม่เป็นไรค่ะ พิมพ์ 'ขอโจทย์' เพื่อเริ่มใหม่ได้เสมอนะคะ ✌️"))
        return

    # 3. กรณีผู้เล่นกำลังตอบคำถาม
    if user_id in user_puzzles:
        puzzle = user_puzzles[user_id]
        
        # เช็กว่าพิมพ์มาแค่ตัวเลขและเครื่องหมายคณิตศาสตร์หรือไม่
        if not re.match(r'^[0-9+\-*/() \.]+$', text):
            line_bot_api.reply_message(event.reply_token, TextSendMessage(text="❌ พิมพ์เฉพาะตัวเลขและเครื่องหมาย +, -, *, /, ( ) เท่านั้นนะคะ"))
            return

        # เช็กว่าใช้ตัวเลขครบและตรงตามโจทย์ไหม
        nums_in_text = sorted([int(n) for n in re.findall(r'\d+', text)])
        sorted_puzzle = sorted(puzzle)
        
        if nums_in_text != sorted_puzzle:
            line_bot_api.reply_message(event.reply_token, TextSendMessage(text=f"❌ ใช้ตัวเลขไม่ตรงกับโจทย์ค่ะ\nโจทย์คือ: {' '.join(map(str, puzzle))}"))
            return

        # คำนวณผลลัพธ์
        try:
            result = eval(text)
            if result == 24:
                del user_puzzles[user_id]
                reply = "✨ ถูกต้องค่ะ! เก่งมาก ✨\nพิมพ์ 'ขอโจทย์' เพื่อเล่นข้อต่อไปได้เลย!"
            else:
                reply = f"😅 ยังไม่ถูกจ้า ผลลัพธ์ที่ได้คือ {result} ลองพยายามใหม่นะ!"
            line_bot_api.reply_message(event.reply_token, TextSendMessage(text=reply))
        except ZeroDivisionError:
            line_bot_api.reply_message(event.reply_token, TextSendMessage(text="❌ ระวังด้วยจ้า ห้ามหารด้วยศูนย์นะ ลองใหม่ๆ"))
        except Exception:
            line_bot_api.reply_message(event.reply_token, TextSendMessage(text="❌ รูปแบบสมการไม่ถูกต้องค่ะ ลองเช็กการใส่วงเล็บอีกครั้งนะคะ"))
    else:
        # 4. กรณีพิมพ์คำอื่นๆ นอกเหนือจากคำสั่ง
        line_bot_api.reply_message(event.reply_token, TextSendMessage(text="พิมพ์ 'ขอโจทย์' เพื่อเริ่มเล่นเกม 24 ได้เลยค่ะ 🧮"))

